package gofiles

import (
	"os"
	"path/filepath"
	"reflect"
	"strings"
	"testing"
)

// writeTree creates files (slash paths relative to root) with the given
// contents.
func writeTree(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for p, body := range files {
		full := filepath.Join(root, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(full), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
}

var tree = map[string]string{
	"go.mod":                 "module example.com/m\n\ngo 1.27\n",
	"main.go":                "// Command m.\npackage main\n\nfunc main() {}\n",
	"a/a.go":                 "// Package a.\npackage a\n",
	"a/a_test.go":            "package a\n",
	"a/b/b.go":               "package b\n",
	"a/b/gen.go":             "// Code generated by x. DO NOT EDIT.\n\npackage b\n",
	"a/testdata/t.go":        "package t\n",
	"a/.hidden/h.go":         "package h\n",
	"a/_skip/s.go":           "package s\n",
	"vendor/v/v.go":          "package v\n",
	"a/notes.txt":            "not go\n",
	"site/assets/copied.go":  "package copied\n",
	"node_modules/x/x.go":    "package x\n",
	"dist/build/out.go":      "package out\n",
	"a/b/c/deeper.go":        "package c\n",
	"a/b/c/deeper_test.go":   "package c\n",
	"other/o.go":             "package other\n",
	"other/sub/included.go":  "package sub\n",
	"other/sub/included2.go": "package sub\n",
}

// paths lists the walked files' paths.
func paths(files []File) []string {
	out := make([]string, len(files))
	for i, f := range files {
		out[i] = f.Path
	}
	return out
}

func TestWalk(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, tree)
	t.Chdir(root)

	tests := []struct {
		name     string
		patterns []string
		want     []string
	}{
		{"default is root only", nil, []string{"main.go"}},
		{"recursive skips test, testdata, hidden, vendor and output dirs", []string{"./..."}, []string{
			"a/a.go", "a/b/b.go", "a/b/c/deeper.go", "a/b/gen.go", "main.go",
			"other/o.go", "other/sub/included.go", "other/sub/included2.go",
		}},
		{"single directory is not recursive", []string{"./a/b"}, []string{"a/b/b.go", "a/b/gen.go"}},
		{"subtree", []string{"./a/b/..."}, []string{"a/b/b.go", "a/b/c/deeper.go", "a/b/gen.go"}},
		{"overlapping patterns list a file once", []string{"./other/...", "./other/sub"}, []string{
			"other/o.go", "other/sub/included.go", "other/sub/included2.go",
		}},
		{"a skipped name is walked when it is the root", []string{"./a/testdata"}, []string{"a/testdata/t.go"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			files, err := Walk(tt.patterns)
			if err != nil {
				t.Fatal(err)
			}
			if got := paths(files); !reflect.DeepEqual(got, tt.want) {
				t.Fatalf("Walk(%q) = %q, want %q", tt.patterns, got, tt.want)
			}
		})
	}
}

func TestWalkFields(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, tree)
	t.Chdir(root)

	files, err := Walk([]string{"./a/b"})
	if err != nil {
		t.Fatal(err)
	}
	gen := map[string]bool{}
	for _, f := range files {
		if f.Dir != "a/b" {
			t.Errorf("%s: Dir = %q, want a/b", f.Path, f.Dir)
		}
		if f.AST == nil || f.Fset == nil || f.AST.Name.Name != "b" {
			t.Errorf("%s: not parsed", f.Path)
		}
		gen[f.Path] = f.Generated
	}
	if want := map[string]bool{"a/b/b.go": false, "a/b/gen.go": true}; !reflect.DeepEqual(gen, want) {
		t.Fatalf("Generated = %v, want %v", gen, want)
	}
}

func TestWalkErrors(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{"bad/bad.go": "package bad\n\nfunc {\n"})
	t.Chdir(root)

	if _, err := Walk([]string{"./bad"}); err == nil {
		t.Error("Walk on a syntax error: want error")
	}
	if _, err := Walk([]string{"./missing/..."}); err == nil {
		t.Error("Walk on a missing directory: want error")
	}
}

func TestModulePath(t *testing.T) {
	dir := t.TempDir()
	write := func(name, body string) string {
		p := filepath.Join(dir, name)
		if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
		return p
	}
	tests := []struct {
		name, body, want string
		wantErr          bool
	}{
		{"plain", "module example.com/m\n\ngo 1.27\n", "example.com/m", false},
		{"quoted with comment line first", "// a module\nmodule \"example.com/q\"\n", "example.com/q", false},
		{"indented", "  module example.com/i  \n", "example.com/i", false},
		{"no module directive", "go 1.27\n", "", true},
	}
	for i, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := ModulePath(write(string(rune('a'+i))+".mod", tt.body))
			if (err != nil) != tt.wantErr || got != tt.want {
				t.Fatalf("ModulePath = %q, %v; want %q, err %v", got, err, tt.want, tt.wantErr)
			}
		})
	}
	if _, err := ModulePath(filepath.Join(dir, "absent.mod")); err == nil {
		t.Error("ModulePath on a missing file: want error")
	}
	// A line longer than bufio.Scanner's limit is a read error, not a
	// silent "no module directive".
	if _, err := ModulePath(write("long.mod", "// "+strings.Repeat("x", 70000)+"\n")); err == nil || strings.Contains(err.Error(), "no module") {
		t.Errorf("ModulePath on an over-long line = %v, want scanner error", err)
	}
}

func TestImportPath(t *testing.T) {
	tests := []struct{ path, want string }{
		{"internal/a/a.go", "example.com/m/internal/a/a.go"},
		{"./internal/a/a.go", "example.com/m/internal/a/a.go"},
		{"main.go", "example.com/m/main.go"},
	}
	for _, tt := range tests {
		if got := ImportPath("example.com/m", tt.path); got != tt.want {
			t.Errorf("ImportPath(%q) = %q, want %q", tt.path, got, tt.want)
		}
	}
}
