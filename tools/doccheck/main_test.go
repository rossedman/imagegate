package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// writeTree creates files (slash paths relative to root) with the given
// contents.
func writeTree(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for p, body := range files {
		full := filepath.Join(root, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(full), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
}

func TestRun(t *testing.T) {
	tests := []struct {
		name     string
		files    map[string]string
		wantCode int
		want     []string // substrings, in output order
	}{
		{
			name: "clean",
			files: map[string]string{
				"p/p.go": "// Package p.\npackage p\n\n// F does f.\nfunc F() {}\n\n// T is t.\ntype T struct{}\n\n// M does m.\nfunc (T) M() {}\n",
				"p/q.go": "package p\n\n// g does g.\nfunc g() {}\n",
			},
			wantCode: 0,
		},
		{
			name: "missing function, method and package docs",
			files: map[string]string{
				"p/p.go": "package p\n\nfunc F() {}\n\ntype T struct{}\n\nfunc (t *T) M() {}\n\ntype G[K any] struct{}\n\nfunc (G[K]) N() {}\n\ntype H[K, V any] struct{}\n\nfunc (*H[K, V]) O() {}\n",
			},
			wantCode: 1,
			want: []string{
				"p/p.go:3:1: F has no doc comment",
				"p/p.go:7:1: T.M has no doc comment",
				"p/p.go:11:1: G.N has no doc comment",
				"p/p.go:15:1: H.O has no doc comment",
				"p: package has no package comment",
				"doccheck: 5 problem(s)",
			},
		},
		{
			name: "tests and generated files are skipped",
			files: map[string]string{
				"p/p.go":      "// Package p.\npackage p\n",
				"p/p_test.go": "package p\n\nfunc helper() {}\n",
				"p/gen.go":    "// Code generated by tool. DO NOT EDIT.\n\npackage p\n\nfunc Gen() {}\n",
				"g/only.go":   "// Code generated by tool. DO NOT EDIT.\n\npackage g\n\nfunc Gen() {}\n",
			},
			wantCode: 0,
		},
		{
			name:     "unparsable file",
			files:    map[string]string{"p/p.go": "package p\n\nfunc {\n"},
			wantCode: 2,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := t.TempDir()
			writeTree(t, root, tt.files)
			t.Chdir(root)

			var stdout, stderr bytes.Buffer
			code := run([]string{"./..."}, &stdout, &stderr)
			if code != tt.wantCode {
				t.Fatalf("run = %d, want %d\nstdout:\n%s\nstderr:\n%s", code, tt.wantCode, &stdout, &stderr)
			}
			out := stdout.String()
			if tt.want == nil && out != "" {
				t.Fatalf("unexpected output:\n%s", out)
			}
			rest := out
			for _, w := range tt.want {
				i := strings.Index(rest, w)
				if i < 0 {
					t.Fatalf("output missing %q (in order):\n%s", w, out)
				}
				rest = rest[i+len(w):]
			}
			if tt.wantCode == 2 && !strings.HasPrefix(stderr.String(), "doccheck: ") {
				t.Fatalf("stderr = %q, want a doccheck: error", &stderr)
			}
		})
	}
}

// TestRepo keeps the repository itself passing, so a missing doc comment
// fails go test as well as CI's doccheck step.
func TestRepo(t *testing.T) {
	t.Chdir("../..")
	var stdout, stderr bytes.Buffer
	if code := run([]string{"./..."}, &stdout, &stderr); code != 0 {
		t.Fatalf("doccheck on the repo = %d:\n%s%s", code, &stdout, &stderr)
	}
}
