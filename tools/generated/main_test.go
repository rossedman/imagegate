package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// writeTree creates files (slash paths relative to root) with the given
// contents.
func writeTree(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for p, body := range files {
		full := filepath.Join(root, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(full), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
}

func TestRun(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"go.mod":             "module example.com/m\n",
		"main.go":            "package main\n",
		"api/types.gen.go":   "// Code generated by oapi-codegen. DO NOT EDIT.\n\npackage api\n",
		"api/handwritten.go": "package api\n",
		"api/b.gen.go":       "// Code generated by x. DO NOT EDIT.\n\npackage api\n",
		"api/gen_test.go":    "// Code generated by x. DO NOT EDIT.\n\npackage api\n",
		"late/notgen.go":     "package late\n\n// Code generated by x. DO NOT EDIT.\n",
	})
	t.Chdir(root)

	var stdout, stderr bytes.Buffer
	if code := run("go.mod", []string{"./..."}, &stdout, &stderr); code != 0 {
		t.Fatalf("run = %d: %s", code, &stderr)
	}
	want := "example.com/m/api/b.gen.go\nexample.com/m/api/types.gen.go\n"
	if stdout.String() != want {
		t.Fatalf("output = %q, want %q", &stdout, want)
	}
}

func TestRunErrors(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"go.mod":     "module example.com/m\n",
		"bad/bad.go": "package bad\n\nfunc {\n",
	})
	t.Chdir(root)

	tests := []struct {
		name, gomod string
		patterns    []string
	}{
		{"missing go.mod", "absent.mod", []string{"./..."}},
		{"unparsable file", "go.mod", []string{"./bad"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var stdout, stderr bytes.Buffer
			if code := run(tt.gomod, tt.patterns, &stdout, &stderr); code != 2 {
				t.Fatalf("run = %d, want 2", code)
			}
			if !strings.HasPrefix(stderr.String(), "generated: ") || stdout.Len() != 0 {
				t.Fatalf("stdout %q, stderr %q", &stdout, &stderr)
			}
		})
	}
}

// TestRepo pins that the repository has no generated Go files today; when
// one is added, CI's coverage filter starts excluding it.
func TestRepo(t *testing.T) {
	t.Chdir("../..")
	var stdout, stderr bytes.Buffer
	if code := run("go.mod", []string{"./..."}, &stdout, &stderr); code != 0 {
		t.Fatalf("run = %d: %s", code, &stderr)
	}
	if stdout.Len() != 0 {
		t.Fatalf("generated files: %s", &stdout)
	}
}
